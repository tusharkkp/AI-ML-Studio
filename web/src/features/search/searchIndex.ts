export function getAllSearchItems(): SearchItem[] {
  // Convert glossary entries into SearchItem format
  const glossaryItems: SearchItem[] = Object.entries(GLOSSARY).map(([key, entry]) => ({
    id: `glossary-${key}`,
    title: entry.term,
    category: 'Glossary',
    unit: entry.unit,
    unitBadge: `U${entry.unit}`,
    desc: entry.definition,
    href: entry.conceptHref ?? '/glossary',
    keywords: [
      entry.term.toLowerCase(),
      key,
      ...(entry.relatedTerms ?? []).map((t) => t.toLowerCase()),
      ...(entry.category ? [entry.category.toLowerCase()] : []),
    ],
  }));

  return [...STATIC_SEARCH_ITEMS, ...glossaryItems];
}
